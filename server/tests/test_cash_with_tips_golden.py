class TestFrozenOnTheClose:
    def test_an_older_close_reads_paid_only(self):
        assert CWT.frozen_paid({"cardTipsFromDrawer": 10}) == Decimal("10.00")
        assert CWT.frozen_unpaid({"cardTipsFromDrawer": 10}) == Decimal("0.00")
        assert CWT.frozen_shortfall({"cardTipsFromDrawer": 10}) is None

    def test_the_parameter_off_freezes_nothing(self):
        assert CWT.frozen_paid({}) is None and CWT.frozen_unpaid({"cardTipsUnpaid": 5}) is None
        assert CWT.frozen_paid(None) is None and CWT.frozen_unpaid("x") is None

    def test_the_new_keys(self):
        till = {"cardTipsFromDrawer": "40.00", "cardTipsUnpaid": "30.00", "cardTipsShortfall": "partial"}
        assert (CWT.frozen_paid(till), CWT.frozen_unpaid(till), CWT.frozen_shortfall(till)) == (
            Decimal("40.00"), Decimal("30.00"), "partial",
        )
        assert CWT.frozen_unpaid({**till, "cardTipsUnpaid": -1}) == Decimal("0")
        assert CWT.frozen_shortfall({**till, "cardTipsShortfall": "ask"}) is None

    def test_shortfall_values(self):
        assert CWT.normalize_shortfall(" Negative ") == "negative"
        assert CWT.normalize_shortfall(None) == CWT.normalize_shortfall("x") == "partial"


class TestASectionsBlock:
    def test_the_total_is_the_sections_expected_cash(self):
        s = {
            "openingCash": "100.00", "expectedCash": "135.00", "cashSalesNet": "50.00",
            "betweenShiftAdjustments": "-5.00", "cardTipsFromDrawer": "20.00", "cardTipsUnpaid": "7.00",
            "cashMovements": {"cashIn": "10.00", "cashOut": "0.00", "deposits": "30.00"},
            "cashWallets": {"walletIn": "0.00", "walletDeposits": "15.00"},
        }
        inp, paid, unpaid = CWT.figures_of_section(s)
        lines, total = CWT.block(inp, paid, unpaid)
        assert total == Decimal("135.00")
        # 100 + 50 + tips + 10 − 30 + 15 − 5 − 20 = 135 → tips 15
        assert inp["cashTips"] == Decimal("15.00")
        assert [l["key"] for l in lines] == [
            "opening", "cashSales", "cashTips", "cashIn", "deposits", "walletDeposits", "between",
            "cardTips", "cardTipsPaid", "cardTipsUnpaid", "total",
        ]

    def test_a_kiosk_or_a_legacy_section_has_no_block(self):
        assert CWT.figures_of_section({"kiosk": True, "openingCash": "0", "expectedCash": "0"}) is None
        assert CWT.figures_of_section({"totalCash": "5"}) is None

    def test_one_drawer_has_no_table(self):
        s = {"openingCash": "0", "expectedCash": "10", "cashSalesNet": "10", "posNumber": 1}
        assert CWT.table_of_sections([s, {"kiosk": True}]) is None
        table = CWT.table_of_sections([s, {**s, "posNumber": 2}])
        assert [r["till"] for r in table["rows"]] == ["קופה 1", "קופה 2"]
        assert table["totals"]["drawerCash"] == "20.00" and table["unpaidTotal"] == "0.00"

"""
"מזומן במגירה כולל טיפים" — the shared rule (P:/specs/x-z-cash-with-tips.md §5).

`tests/fixtures/x_z_cash_with_tips_golden.json` is generated by the spec's reference implementation
and is byte-identical in pos-server (here, read by the client's test too), kiosk-desktop
(`test/fixtures/`) and pos-android (`app/src/test/resources/`); every test that reads it pins the
SHA-256 of its bytes. Every case is run here, every field compared.
"""
from __future__ import annotations

import hashlib
import json
from decimal import Decimal
from pathlib import Path

import pytest

from app.services import cash_with_tips as CWT

GOLDEN = Path(__file__).parent / "fixtures" / "x_z_cash_with_tips_golden.json"
GOLDEN_SHA256 = "1f87e1c89566b147a4c097febe5c789b73f0a16340f94275757eb31f82c0eb98"
KIOSK_COPY = Path(__file__).resolve().parents[2] / "kiosk-desktop" / "test" / "fixtures" / GOLDEN.name


def _doc():
    return json.loads(GOLDEN.read_bytes().decode("utf-8"))


def test_the_fixture_is_the_pinned_bytes():
    assert hashlib.sha256(GOLDEN.read_bytes()).hexdigest() == GOLDEN_SHA256


def test_the_windows_till_has_the_same_bytes():
    if not KIOSK_COPY.exists():
        pytest.skip("kiosk-desktop is not beside server")
    assert KIOSK_COPY.read_bytes() == GOLDEN.read_bytes()


def test_the_labels_are_the_golden_ones():
    assert CWT.LABELS == _doc()["labels"]


@pytest.mark.parametrize("case", _doc()["drawerCases"], ids=lambda c: c["name"])
def test_every_drawer_case(case):
    assert CWT.drawer_case(case["input"]) == case["expect"]


@pytest.mark.parametrize("case", _doc()["drawerCases"], ids=lambda c: c["name"])
def test_the_block_total_is_the_expected_cash(case):
    """The total is the expected cash after the payout: available − paid, line by line."""
    e = case["expect"]
    paid = Decimal(e["paid"]) if e["paid"] is not None else Decimal("0")
    assert Decimal(e["total"]) == Decimal(e["available"]) - paid
    added = sum(
        (Decimal(l["amount"]) for l in e["lines"] if l["key"] not in ("cardTips", "cardTipsUnpaid", "total", "short")),
        Decimal("0"),
    )
    assert added == Decimal(e["total"])


@pytest.mark.parametrize("case", _doc()["tillTableCases"], ids=lambda c: c["name"])
def test_every_till_table_case(case):
    assert CWT.till_table_case(case["tills"], case["showDrawerCash"]) == case["expect"]



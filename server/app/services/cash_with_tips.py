def dec(value: Any) -> Optional[Decimal]:
    """A money value as a Decimal; None for none (or anything that is not a finite number)."""
    if value is None or value == "" or isinstance(value, bool):
        return None
    try:
        d = value if isinstance(value, Decimal) else Decimal(str(value))
    except (InvalidOperation, ValueError):
        return None
    return d if d.is_finite() else None


def money(value: Optional[Decimal]) -> Optional[str]:
    """Two places, "-" for a negative; None stays None."""
    return None if value is None else str(Decimal(value).quantize(CENT))


def _z(value: Any) -> Decimal:
    d = dec(value)
    return ZERO if d is None else d


def normalize_shortfall(value: Any) -> str:
    """The parameter's value as one of its options; anything else is the default (`partial`)."""
    text = str(value or "").strip().lower()
    return text if text in SHORTFALL_OPTIONS else SHORTFALL_DEFAULT


class Payout(NamedTuple):
    #: Paid from the drawer / owed to staff — None when the parameter is off.
    paid: Optional[Decimal]
    unpaid: Optional[Decimal]
    #: The resolved mode the close freezes (`partial` / `negative`; `ask` → the choice) — None when off.
    mode: Optional[str]
    #: `ask`, short and no choice made yet: an X previews `partial`, the close must ask.
    needs_choice: bool


def payout(param: bool, shortfall: Any, ask_choice: Any, available: Any, card_tips: Any) -> Payout:
    """
    §2: `available` is the expected cash before the tips payout; `card_tips` the shift's card tips
    net of tip reversals (floored at 0 here).
    """
    if not param:
        return Payout(None, None, None, False)
    tips = max(_z(card_tips), ZERO)
    room = max(_z(available), ZERO)
    short = tips > room
    needs_choice = False
    mode = normalize_shortfall(shortfall)
    if mode == ASK:
        choice = str(ask_choice or "").strip().lower()
        if not short:
            mode = PARTIAL  # nothing to choose: both pay everything; frozen as partial
        elif choice in (PARTIAL, NEGATIVE):
            mode = choice
        else:
            mode = PARTIAL  # previewed until the manager chooses at the close
            needs_choice = True
    paid = tips if mode == NEGATIVE else min(tips, room)
    return Payout(paid, tips - paid, mode, needs_choice)


def _movements(inp: Dict[str, Any]) -> Optional[Tuple[Decimal, Decimal, Decimal]]:
    mv = inp.get("movements")
    if not isinstance(mv, dict):
        return None
    return _z(mv.get("cashIn")), _z(mv.get("cashOut")), _z(mv.get("deposits"))


def _wallet(inp: Dict[str, Any]) -> Tuple[Decimal, Decimal]:
    w = inp.get("wallet") if isinstance(inp.get("wallet"), dict) else {}
    return _z(w.get("walletIn")), _z(w.get("walletDeposits"))


def available_of(inp: Dict[str, Any]) -> Decimal:
    """The expected cash before the tips payout (§2 "available")."""
    win, wdep = _wallet(inp)
    total = (
        _z(inp.get("opening")) + _z(inp.get("cashSales")) - _z(inp.get("deviceCash")) + _z(inp.get("cashTips"))
        + wdep - win + _z(inp.get("between"))
    )
    mv = _movements(inp)
    if mv is not None:
        total += mv[0] - mv[1] - mv[2]
    return total


def block(
    inp: Dict[str, Any],
    paid: Optional[Decimal],
    unpaid: Optional[Decimal],
    *,
    show: Optional[bool] = None,
    labels: Optional[Dict[str, str]] = None,
) -> Tuple[List[Dict[str, Any]], Decimal]:
    """
    The block's lines `[{key, label, amount, bold, warn}]` and its total, from figures (frozen or
    computed). `paid` None: the parameter was off — no card tips lines. `show` (default: the
    input's `showDrawerCash`, else True): whether the expected cash may be seen — without it the
    `total` / `short` lines are dropped, every other line stays.
    """
    L = labels or LABELS
    lines: List[Dict[str, Any]] = []

    def add(key: str, amount: Decimal, bold: bool = False, warn: bool = False) -> None:
        lines.append({"key": key, "label": L[key], "amount": money(amount), "bold": bold, "warn": warn})

    opening, sales, ctips = _z(inp.get("opening")), _z(inp.get("cashSales")), _z(inp.get("cashTips"))
    total = opening + sales + ctips
    add("opening", opening)
    add("cashSales", sales)
    # "מזומן במכשיר": inside the cash takings, in the device — never the drawer's.
    device = _z(inp.get("deviceCash"))
    if device != 0:
        add("deviceCash", -device)
        total -= device
    add("cashTips", ctips)
    mv = _movements(inp)
    if mv is not None:
        cin, cout, dep = mv
        if cin != 0:
            add("cashIn", cin)
        if cout != 0:
            add("cashOut", -cout)
        if dep != 0:
            add("deposits", -dep)
        total += cin - cout - dep
    win, wdep = _wallet(inp)
    if win != 0:
        add("walletIn", -win)
    if wdep != 0:
        add("walletDeposits", wdep)
    total += wdep - win
    between = _z(inp.get("between"))
    if between != 0:
        add("between", between)
    total += between
    if paid is not None:
        owed = unpaid if unpaid is not None else ZERO
        add("cardTips", paid + owed)
        add("cardTipsPaid", -paid)
        if owed > 0:
            add("cardTipsUnpaid", owed)
        total -= paid
    visible = inp.get("showDrawerCash", True) if show is None else show
    if visible:
        add("total", total, bold=True, warn=total < 0)
        if total < 0:
            add("short", -total, bold=True, warn=True)
    return lines, total


def drawer_case(inp: Dict[str, Any]) -> Dict[str, Any]:
    """One X / Z drawer from raw figures: the golden's `expect` (the payout computed here)."""
    available = available_of(inp)
    pay = payout(bool(inp.get("param")), inp.get("shortfall", PARTIAL), inp.get("askChoice"), available, inp.get("cardTips"))
    lines, total = block(inp, pay.paid, pay.unpaid)
    return {
        "available": money(available),
        "paid": money(pay.paid),
        "unpaid": money(pay.unpaid),
        "frozenShortfall": pay.mode,
        "needsChoice": pay.needs_choice,
        "total": money(total),
        "short": total < 0,
        "lines": lines,
    }


class TillRow(NamedTuple):
    till: str
    #: The block's input (opening, cashSales, cashTips, movements, wallet, between).
    input: Dict[str, Any]
    paid: Optional[Decimal]
    unpaid: Optional[Decimal]


def till_table(rows: Sequence[TillRow], show: bool = True, labels: Optional[Dict[str, str]] = None) -> Dict[str, Any]:
    """
    §3 "מזומן במגירה לפי קופה": per till its cash sales, cash tips, paid, unpaid and drawer (the
    block's total — None when hidden), the totals row (paid / unpaid None when no till froze the
    parameter), the day's unpaid card tips (`unpaidTotal`, 0.00 when none) and the summary shown first
    (`summary`: totalCash, tips, unpaid, netCash and its lines).
    """
    out_rows: List[Dict[str, Any]] = []
    sales_sum = tips_sum = drawer_sum = ZERO
    paid_sum: Optional[Decimal] = None
    unpaid_sum: Optional[Decimal] = None
    any_short = False
    available_sum = ZERO
    for r in rows:
        _lines, total = block(r.input, r.paid, r.unpaid, show=False)
        # The cash in the drawer before any tip was paid out of it.
        available_sum += total + (r.paid if r.paid is not None else ZERO)
        sales, ctips = _z(r.input.get("cashSales")), _z(r.input.get("cashTips"))
        out_rows.append({
            "till": r.till, "cashSales": money(sales), "cashTips": money(ctips),
            "cardTipsPaid": money(r.paid),
            "cardTipsUnpaid": money(None if r.paid is None else (r.unpaid if r.unpaid is not None else ZERO)),
            "drawerCash": money(total) if show else None, "short": bool(show and total < 0),
        })
        sales_sum += sales
        tips_sum += ctips
        if r.paid is not None:
            paid_sum = (paid_sum or ZERO) + r.paid
            unpaid_sum = (unpaid_sum or ZERO) + (r.unpaid if r.unpaid is not None else ZERO)
        drawer_sum += total
        any_short = any_short or total < 0
    # §3 "Shop / area Z summary first": the cash of all the drawers before any payout, the tips that
    # belong to staff (cash tips + card tips paid from the drawers), the card tips still owed, and
    # what is left — business cash ("מזומן נטו אחרי טיפים").
    tips = tips_sum + (paid_sum or ZERO)
    owed_all = unpaid_sum or ZERO
    net = available_sum - tips - owed_all
    summary: List[Dict[str, Any]] = []

    def sadd(key: str, amount: Decimal, bold: bool = False, warn: bool = False) -> None:
        summary.append({"key": key, "label": (labels or LABELS)[key], "amount": money(amount), "bold": bold, "warn": warn})

    if show:
        sadd("summaryCash", available_sum)
    sadd("summaryTips", tips)
    if owed_all > 0:
        sadd("summaryUnpaid", owed_all)
    if show:
        sadd("summaryNet", net, bold=True, warn=net < 0)
    return {
        "rows": out_rows,
        "totals": {
            "cashSales": money(sales_sum), "cashTips": money(tips_sum),
            "cardTipsPaid": money(paid_sum), "cardTipsUnpaid": money(unpaid_sum),
            "drawerCash": money(drawer_sum) if show else None,
            "anyShort": bool(show and any_short),
        },
        "unpaidTotal": money(unpaid_sum if unpaid_sum is not None else ZERO),
        "summary": {
            "totalCash": money(available_sum) if show else None,
            "tips": money(tips),
            "unpaid": money(owed_all),
            "netCash": money(net) if show else None,
            "lines": summary,
        },
    }


def till_table_case(tills: Sequence[Dict[str, Any]], show: bool = True) -> Dict[str, Any]:
    """The golden's `tillTableCases[].expect`: each till's payout computed from its raw figures."""
    rows = []
    for t in tills:
        inp = t["input"]
        pay = payout(bool(inp.get("param")), inp.get("shortfall", PARTIAL), inp.get("askChoice"),
                     available_of(inp), inp.get("cardTips"))
        rows.append(TillRow(t["till"], inp, pay.paid, pay.unpaid))
    return till_table(rows, show)


# ── A shift's close and a Z's figures ───────────────────────────────────────


def frozen_paid(till: Any) -> Optional[Decimal]:
    """The paid amount a close froze (`till.cardTipsFromDrawer`); None without it or for nonsense."""
    if not isinstance(till, dict):
        return None
    d = dec(till.get(PAID_KEY))
    if d is None or d < 0:
        return None
    return d.quantize(CENT)


def frozen_unpaid(till: Any) -> Optional[Decimal]:
    """
    The unpaid amount a close froze (`till.cardTipsUnpaid`): None when the close froze no paid
    amount (the parameter was off); an older close (paid only) reads 0.
    """
    if frozen_paid(till) is None:
        return None
    d = dec(till.get(UNPAID_KEY))
    if d is None or d < 0:
        return ZERO
    return d.quantize(CENT)


def frozen_shortfall(till: Any) -> Optional[str]:
    """The resolved mode a close froze (`partial` / `negative`); None when absent."""
    if not isinstance(till, dict) or frozen_paid(till) is None:
        return None
    text = str(till.get(FROZEN_SHORTFALL_KEY) or "").strip().lower()
    return text if text in (PARTIAL, NEGATIVE) else None


def figures_of_section(s: Dict[str, Any]) -> Optional[Tuple[Dict[str, Any], Optional[Decimal], Optional[Decimal]]]:
    """
    A Z's (or X's) section — one till's, or a header read the same way — as the block's input and
    its frozen paid / unpaid: `(input, paid, unpaid)`, None when it carries no drawer (a legacy Z,
    a kiosk). The block's total is the section's `expectedCash` exactly: the cash tips line is what
    the expected holds beside the other lines (Σ of the shifts' cash tips on a Z the cloud built).
    """
    if not isinstance(s, dict) or s.get("kiosk"):
        return None
    opening, expected = dec(s.get("openingCash")), dec(s.get("expectedCash"))
    if opening is None or expected is None:
        return None
    sales = dec(s.get("cashSalesNet"))
    if sales is None:
        sales = _z(s.get("totalCash"))
    mv = s.get("cashMovements") if isinstance(s.get("cashMovements"), dict) else None
    w = s.get("cashWallets") if isinstance(s.get("cashWallets"), dict) else None
    paid = dec(s.get(PAID_KEY))
    unpaid = None if paid is None else (dec(s.get(UNPAID_KEY)) or ZERO)
    inp: Dict[str, Any] = {
        "opening": opening,
        "cashSales": sales,
        # "מזומן במכשיר" (absent: none — a Z from before it, or no cash device): out of `expectedCash` already.
        "deviceCash": _z(s.get(DEVICE_CASH_KEY)),
        "movements": None if mv is None else {k: _z(mv.get(k)) for k in ("cashIn", "cashOut", "deposits")},
        "wallet": {"walletIn": _z((w or {}).get("walletIn")), "walletDeposits": _z((w or {}).get("walletDeposits"))},
        "between": _z(s.get("betweenShiftAdjustments")),
    }
    inp["cashTips"] = ZERO
    _lines, without_tips = block(inp, paid, unpaid, show=False)
    inp["cashTips"] = expected - without_tips
    return inp, paid, unpaid


def till_label(s: Dict[str, Any]) -> str:
    """A till's name in the table: "קופה 3" (its register number), else its name."""
    pos = s.get("posNumber")
    if pos not in (None, ""):
        return f"קופה {pos}"
    return str(s.get("machineName") or s.get("label") or "קופה").strip() or "קופה"


def drawer_sections(sections: Sequence[Any]) -> List[Dict[str, Any]]:
    """The sections that are a drawer (no kiosk, a drawer figure), one per till in their order."""
    return [s for s in sections if isinstance(s, dict) and figures_of_section(s) is not None]


def table_of_sections(
    sections: Sequence[Any], show: bool = True, labels: Optional[Dict[str, str]] = None,
) -> Optional[Dict[str, Any]]:
    """The per-till table of a Z / X over several drawers; None for one drawer or none (§3)."""
    drawers = drawer_sections(sections)
    if len(drawers) < 2:
        return None
    rows = []
    for s in drawers:
        inp, paid, unpaid = figures_of_section(s)  # type: ignore[misc]
        rows.append(TillRow(till_label(s), inp, paid, unpaid))
    return till_table(rows, show, labels)

"""
"מזומן במגירה כולל טיפים" — the cash in the drawer, tips included, on every X and Z
(P:/specs/x-z-cash-with-tips.md; the contract is that spec and its golden
`tests/fixtures/x_z_cash_with_tips_golden.json`, generated by the reference implementation — the
same rule as pos-android `domain/CashWithTips.kt`, client `src/lib/cashWithTips.ts` and the Windows
till).

Three things, all pure (Decimal, two places — never a float):

* **The payout** (§2): how much of the shift's card tips the drawer pays staff
  (`cashDrawer.cardTipsFromDrawer` on) under `cashDrawer.cardTipsShortfall` — `partial` pays only
  what the drawer holds (never takes it below zero), `negative` pays everything, `ask` lets the
  manager choose at the close, only when short. The till freezes the result on the close
  (`till.cardTipsFromDrawer` = paid, `cardTipsUnpaid`, `cardTipsShortfall`); the cloud never
  recomputes a closed shift's payout from the live parameter.
* **The block** (§1): the lines "קופה פותחת … = מזומן במגירה (כולל טיפים)" — a presentation of the
  report's expected cash, which its total equals exactly (the card tips lines are information,
  only the paid amount comes off). Shown always; `total` / `short` only where the expected cash may
  be seen.
* **The per-till table** (§3): a shop / area Z or X — each drawer apart (one till's cash never
  pays another till's tips), a totals row, and the unpaid card tips of the day.

Inputs are the golden's: `{opening, cashSales, deviceCash, cashTips, cardTips, movements (None = not
part of this expected), wallet, between, param, shortfall, askChoice, showDrawerCash}`, money as decimal
strings or Decimals. `cashSales` is every cash taking (the X's / Z's cash); `deviceCash` ("מזומן במכשיר",
absent = 0) the part of it a cash device (CashMag recycler / PayLink station) took — in the device, never
in the drawer: its own line, off the total and off what the drawer may pay tips from.
"""
from __future__ import annotations

from decimal import Decimal, InvalidOperation
from typing import Any, Dict, List, NamedTuple, Optional, Sequence, Tuple

ZERO = Decimal("0")
CENT = Decimal("0.01")

